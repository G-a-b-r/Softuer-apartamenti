def generate_units():
    units = {}

    for building in BUILDINGS:
        apt_count = len(PRICES[building])
        building_units = []
        for i in range(apt_count):
            building_units.append({
                'id': BUILDING_IDS[building] + str(i + 1),
                'name': 'Апартамент ' + str(i + 1),
                'type': 'apartment',
                'sqm': SIZES[i],
                'price': PRICES[building][i],
                'status': 'free',
                'aptType': TYPES[building][i],
            })
        units[building] = building_units

    parking_units = []
    for i in range(1, 192):
        unit_id = 'ПМ ' + str(i) + (' инвалидно' if i in PARKING_DISABLED else '')
        parking_units.append({
            'id': unit_id,
            'name': 'Паркомясто ' + str(i),
            'type': 'parking',
            'sqm': 12,
            'price': 8500,
            'status': 'free',
        })
    units['parking'] = parking_units

    return units